C     SINX -- DSIN AND DCOS AT 100,000 ARGUMENTS EACH, THE BITS OF
C     THEIR RESULTS FOLDED INTO A HASH (ISSUE #3): THE ONES IN
C     ASSEMBLER DO THE SAME FLOATING-POINT OPERATIONS IN THE SAME ORDER
C     AS THE ONES IN C, SO THEY GIVE THE SAME HASHES.  THE ARGUMENTS ARE
C     RANDOM HFP LONGS (XORSHIFT32) OF EITHER SIGN WITH CHARACTERISTICS
C     34-45 (1E-10 TO JUST UNDER 2**20, WHERE THE ASSEMBLER HANDS OVER
C     TO C), ONE IN A HUNDRED PUSHED UP BY A WHOLE NUMBER.  AND A FEW
C     WHOSE VALUES ARE KNOWN, AND THOSE IT GIVES TO C.  SELF-CHECKING
C     FOR THOSE: " >NAME OK" OR " >NAME BAD"; THE HASHES ARE PRINTED,
C     " >HASHN" AND THE VALUE.
      PROGRAM SINX
      DOUBLE PRECISION X, Y
      INTEGER IX(2), IY(2), IS, IH, I, K, NBAD, IC
      EQUIVALENCE (X, IX(1)), (Y, IY(1))
      NBAD = 0
      CALL CHK('SIN0   ', DSIN(0.0D0) .EQ. 0.0D0, NBAD)
      CALL CHK('COS0   ', DCOS(0.0D0) .EQ. 1.0D0, NBAD)
      CALL CHK('ODD    ', DSIN(-0.5D0) .EQ. -DSIN(0.5D0), NBAD)
      CALL CHK('EVEN   ', DCOS(-0.5D0) .EQ. DCOS(0.5D0), NBAD)
      CALL CHK('PYTHAG ', DABS(DSIN(0.7D0)**2 + DCOS(0.7D0)**2 - 1.0D0)
     1    .LT. 1.0D-15, NBAD)
C     ITS SERIES UNDERFLOWS, AS THE C ONE'S DID, WITHOUT A WORD
      CALL CHK('TINY   ', DSIN(1.0D-40) .EQ. 1.0D-40, NBAD)
C     THE ARGUMENTS THE ASSEMBLER HANDS TO C: PAST FORTLIB'S LIMIT (A
C     MESSAGE, AND SQRT(2)/2), AND 2**20 OR MORE (PAYNE AND HANEK)
      CALL CHK('HUGEARG', DABS(DSIN(1.0D20) - 0.70710678118654752D0)
     1    .LT. 1.0D-15, NBAD)
      CALL CHK('BIGARG ', DABS(DSIN(2.0D6) + 0.65571431556347D0)
     1    .LT. 1.0D-13, NBAD)
      IS = 12345
      DO 30 K = 1, 2
        IH = 0
        DO 10 I = 1, 100000
          CALL XSH(IS)
          IC = 52 + MOD(IAND(IS, 255), 18)
          IX(1) = IOR(ISHFT(IC, 24), IAND(IS, 16777215))
          IF (IAND(IS, 256) .NE. 0) IX(1) = IOR(IX(1), ISHFT(1, 31))
          IX(1) = IOR(IX(1), 1048576)
          CALL XSH(IS)
          IX(2) = IS
          IF (MOD(I, 100) .EQ. 0) X = X + DBLE(MOD(IS, 1000000))
          IF (K .EQ. 1) Y = DSIN(X)
          IF (K .EQ. 2) Y = DCOS(X)
          IH = IEOR(ISHFTC(IH, 5, 32), IY(1))
          IH = IEOR(ISHFTC(IH, 7, 32), IY(2))
   10   CONTINUE
        WRITE (6,1) K, IH
    1   FORMAT(' >HASH', I1, 1X, Z8)
   30 CONTINUE
      WRITE (6,2) NBAD
    2 FORMAT(' >BAD ', I2)
      END
      SUBROUTINE XSH(IS)
      INTEGER IS
      IS = IEOR(IS, ISHFT(IS, 13))
      IS = IEOR(IS, ISHFT(IS, -17))
      IS = IEOR(IS, ISHFT(IS, 5))
      END
      SUBROUTINE CHK(NAME, OK, NBAD)
      CHARACTER*7 NAME
      LOGICAL OK
      INTEGER NBAD
      IF (OK) THEN
        WRITE (6,1) NAME
    1   FORMAT(' >', A7, ' OK')
      ELSE
        WRITE (6,2) NAME
    2   FORMAT(' >', A7, ' BAD')
        NBAD = NBAD + 1
      END IF
      END
