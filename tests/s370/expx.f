C     EXPX -- DEXP, DLOG, DLOG10 AND X**Y AT 100,000 ARGUMENTS EACH,
C     THE BITS OF THEIR RESULTS FOLDED INTO A HASH (ISSUE #3): THE ONES
C     IN ASSEMBLER DO THE SAME FLOATING-POINT OPERATIONS IN THE SAME
C     ORDER AS THE ONES IN C, SO THEY GIVE THE SAME HASHES.  DEXP'S
C     ARGUMENTS ARE RANDOM IN (-180, 174.6) (XORSHIFT32); DLOG'S AND
C     DLOG10'S RANDOM POSITIVE HFP LONGS OF EVERY CHARACTERISTIC; X**Y'S
C     BASES RANDOM IN (1E-5, 1E5) AND EXPONENTS IN (-14, 14), INSIDE
C     THE EXPONENTIAL'S RANGE.  AND A FEW WHOSE VALUES ARE KNOWN, AND
C     THOSE THE ASSEMBLER GIVES TO C: FORTLIB'S MESSAGES.  SELF-CHECKING
C     FOR THOSE: " >NAME OK" OR " >NAME BAD"; THE HASHES ARE PRINTED,
C     " >HASHN" AND THE VALUE.
      PROGRAM EXPX
      DOUBLE PRECISION X, Y, Z, U
      INTEGER IX(2), IY(2), IS, IH, I, K, NBAD
      EQUIVALENCE (X, IX(1)), (Y, IY(1))
      NBAD = 0
      CALL CHK('EXP0   ', DEXP(0.0D0) .EQ. 1.0D0, NBAD)
      CALL CHK('EXP1   ', DABS(DEXP(1.0D0) - 2.718281828459045D0)
     1    .LT. 1.0D-15, NBAD)
      CALL CHK('EXPLOW ', DEXP(-200.0D0) .EQ. 0.0D0, NBAD)
      CALL CHK('LOG1   ', DLOG(1.0D0) .EQ. 0.0D0, NBAD)
      CALL CHK('LOG10  ', DABS(DLOG10(100.0D0) - 2.0D0) .LT. 1.0D-15,
     1    NBAD)
      Z = 2.0D0
      U = 10.0D0
      CALL CHK('POW2   ', Z ** U .EQ. 1024.0D0, NBAD)
      U = 0.0D0
      CALL CHK('POW0   ', Z ** U .EQ. 1.0D0, NBAD)
C     AN UNNORMALIZED ARGUMENT, 1/16 AS X'4101000000000000': ITS LOG IS
C     1/16'S (M_FREXP CALLED ITSELF FOREVER ON ONE)
      IX(1) = 1090584576
      IX(2) = 0
      CALL CHK('UNNORM ', DLOG(X) .EQ. DLOG(0.0625D0), NBAD)
C     THE C ENTRIES: PAST EXP'S LIMIT, A LOG OF A NEGATIVE NUMBER, A
C     ZERO BASE, A POWER PAST THE LIMIT (MESSAGES, AND FORTLIB'S
C     FIXUPS)
      CALL CHK('EXPBIG ', DEXP(200.0D0) .GT. 7.0D75, NBAD)
      CALL CHK('LOGNEG ', DABS(DLOG(-1.0D2) - DLOG(1.0D2)) .EQ. 0.0D0,
     1    NBAD)
      Z = 0.0D0
      U = 2.0D0
      CALL CHK('POWZERO', Z ** U .EQ. 0.0D0, NBAD)
      Z = 10.0D0
      U = 100.0D0
      CALL CHK('POWBIG ', Z ** U .GT. 7.0D75, NBAD)
      IS = 12345
      DO 30 K = 1, 4
        IH = 0
        DO 10 I = 1, 100000
          CALL XSH(IS)
          IF (K .EQ. 1) THEN
            X = DBLE(IAND(IS, 2147483647)) / 2147483648.0D0
            CALL XSH(IS)
            X = X + DBLE(IAND(IS, 1048575)) / 1.0D12
            X = X * 354.6D0 - 180.0D0
            Y = DEXP(X)
          ELSE IF (K .LE. 3) THEN
            IX(1) = IOR(IAND(IS, 2147483647), 1048576)
            CALL XSH(IS)
            IX(2) = IS
            IF (K .EQ. 2) Y = DLOG(X)
            IF (K .EQ. 3) Y = DLOG10(X)
          ELSE
            X = DBLE(IAND(IS, 2147483647)) / 2147483648.0D0
            Z = 10.0D0 ** (10.0D0 * X - 5.0D0)
            CALL XSH(IS)
            U = (DBLE(IAND(IS, 2147483647)) / 2147483648.0D0 - 0.5D0)
     1          * 28.0D0
            Y = Z ** U
          END IF
          IH = IEOR(ISHFTC(IH, 5, 32), IY(1))
          IH = IEOR(ISHFTC(IH, 7, 32), IY(2))
   10   CONTINUE
        WRITE (6,1) K, IH
    1   FORMAT(' >HASH', I1, 1X, Z8)
   30 CONTINUE
      WRITE (6,2) NBAD
    2 FORMAT(' >BAD ', I2)
      END
      SUBROUTINE XSH(IS)
      INTEGER IS
      IS = IEOR(IS, ISHFT(IS, 13))
      IS = IEOR(IS, ISHFT(IS, -17))
      IS = IEOR(IS, ISHFT(IS, 5))
      END
      SUBROUTINE CHK(NAME, OK, NBAD)
      CHARACTER*7 NAME
      LOGICAL OK
      INTEGER NBAD
      IF (OK) THEN
        WRITE (6,1) NAME
    1   FORMAT(' >', A7, ' OK')
      ELSE
        WRITE (6,2) NAME
    2   FORMAT(' >', A7, ' BAD')
        NBAD = NBAD + 1
      END IF
      END
