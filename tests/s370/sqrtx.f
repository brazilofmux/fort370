C     SQRTX -- DSQRT AT 200,000 ARGUMENTS, THE BITS OF ITS RESULTS
C     FOLDED INTO A HASH: THE ROOT CORRECTLY ROUNDED IS ONE NUMBER, SO
C     ANY TWO CORRECT DSQRTS GIVE THE SAME HASH (ISSUE #3: THE ONE IN
C     ASSEMBLER AGAINST THE ONE IN C).  THE ARGUMENTS ARE RANDOM HFP
C     LONGS (XORSHIFT32): EVERY CHARACTERISTIC, A NORMALIZED FRACTION;
C     THEN AS MANY WHOSE FRACTION MAY BE UNNORMALIZED.  AND A FEW
C     WHOSE ROOTS ARE KNOWN.  SELF-CHECKING FOR THOSE: " >NAME OK" OR
C     " >NAME BAD"; THE HASHES ARE PRINTED, " >HASHN" AND THE VALUE.
      PROGRAM SQRTX
      DOUBLE PRECISION X, Y
      INTEGER IX(2), IY(2), IS, IH, I, K, NBAD
      EQUIVALENCE (X, IX(1)), (Y, IY(1))
      NBAD = 0
      CALL CHK('FOUR   ', DSQRT(4.0D0) .EQ. 2.0D0, NBAD)
      CALL CHK('QUART  ', DSQRT(0.25D0) .EQ. 0.5D0, NBAD)
      CALL CHK('SIXTEEN', DSQRT(256.0D0) .EQ. 16.0D0, NBAD)
      CALL CHK('ZERO   ', DSQRT(0.0D0) .EQ. 0.0D0, NBAD)
      CALL CHK('BIG    ', DSQRT(1.0D74) .EQ. 1.0D37, NBAD)
      CALL CHK('SMALL  ', DSQRT(1.0D-74) .EQ. 1.0D-37, NBAD)
      IS = 12345
      DO 20 K = 1, 2
        IH = 0
        DO 10 I = 1, 100000
          CALL XSH(IS)
          IX(1) = IAND(IS, 2147483647)
          IF (K .EQ. 1) IX(1) = IOR(IX(1), 1048576)
          CALL XSH(IS)
          IX(2) = IS
          Y = DSQRT(X)
          IH = IEOR(ISHFTC(IH, 5, 32), IY(1))
          IH = IEOR(ISHFTC(IH, 7, 32), IY(2))
   10   CONTINUE
        WRITE (6,1) K, IH
    1   FORMAT(' >HASH', I1, 1X, Z8)
   20 CONTINUE
      WRITE (6,2) NBAD
    2 FORMAT(' >BAD ', I2)
      END
      SUBROUTINE XSH(IS)
      INTEGER IS
      IS = IEOR(IS, ISHFT(IS, 13))
      IS = IEOR(IS, ISHFT(IS, -17))
      IS = IEOR(IS, ISHFT(IS, 5))
      END
      SUBROUTINE CHK(NAME, OK, NBAD)
      CHARACTER*7 NAME
      LOGICAL OK
      INTEGER NBAD
      IF (OK) THEN
        WRITE (6,1) NAME
    1   FORMAT(' >', A7, ' OK')
      ELSE
        WRITE (6,2) NAME
    2   FORMAT(' >', A7, ' BAD')
        NBAD = NBAD + 1
      END IF
      END
