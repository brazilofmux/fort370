C     AN INTEGER READ BEFORE ANYTHING ASSIGNED IT IS UNDEFINED, BUT A
C     PROGRAM THAT DOES IT MUST STILL COMPILE.  THE CODE GENERATOR HAD
C     NO REGISTER FOR SUCH A VALUE IN A COMPARE OR AN ARITHMETIC IF AND
C     STOPPED WITH "MISSING OPERAND"; NOW THE VALUE IS 0.  WHAT THIS
C     PRINTS DOES NOT DEPEND ON THE VALUE.
      INTEGER I, J, K, N
      IF (I) 1,2,3
1     CONTINUE
2     CONTINUE
3     CONTINUE
      IF (J.GT.0) N=1
      DO 10 N=1,3
      K=K+1
10    CONTINUE
      WRITE(6,100)
100   FORMAT(1X,'>UNDEFINT OK')
      END
