C     DUMMY PROCEDURES: A SUBROUTINE AND A FUNCTION PASSED AS ACTUAL
C     ARGUMENTS, AN INTRINSIC PASSED AS ONE, AND A DUMMY NAMED LIKE
C     AN INTRINSIC (NINT), WHICH IS THEN NOT THE INTRINSIC.
      EXTERNAL FS335,FF330
      INTRINSIC IABS
      COMMON /BLK1/ IVCN01,RVCN01
      REAL RVON01
      RVON01=3.5
      CALL FS334(FS335,RVON01)
      WRITE(6,100) 'SUBR',RVCN01
      CALL FS333(FF330,5)
      WRITE(6,101) 'FUNC',IVCN01
      CALL FS333(IABS,-7)
      WRITE(6,101) 'IABS',IVCN01
      WRITE(6,101) 'NINT',NINT(2.6)
  100 FORMAT(' >',A4,F8.3)
  101 FORMAT(' >',A4,I8)
      STOP
      END
      SUBROUTINE FS334(IDON06,RDON03)
      COMMON /BLK1/ IVCN01,RVCN01
      CALL IDON06(RDON03)
      RVCN01=RDON03+1.0
      RETURN
      END
      SUBROUTINE FS335(RDON04)
      RDON04=RDON04+1.0
      RETURN
      END
      SUBROUTINE FS333(NINT,IDON03)
      COMMON /BLK1/ IVCN01,RVCN01
      IVCN01=NINT(IDON03)+1
      RETURN
      END
      INTEGER FUNCTION FF330(IDON02)
      FF330=IDON02+1
      RETURN
      END
