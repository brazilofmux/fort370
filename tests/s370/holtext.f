C     TEXT IN NUMERIC VARIABLES, AS FORTRAN 66 AND IBM'S COMPILERS KEEP
C     IT: HOLLERITH DATA IN INTEGER, REAL AND DOUBLE PRECISION ITEMS,
C     WRITTEN AND READ WITH A EDITING.  AW TAKES THE FIRST W BYTES OF
C     THE ITEM AS IT LIES IN STORAGE, OR PADS ON THE LEFT IF W IS
C     LARGER; ON INPUT A LARGER W KEEPS THE RIGHTMOST BYTES.  THE
C     RUNTIME HAD HANDED SUCH AN ITEM TO THE NUMBER WRITER, WHICH
C     PRINTED STARS, AND STOPPED ON INPUT.
      INTEGER D/1H5/, E(2)/1HA,4HWXYZ/, R, S
      REAL X/4HABCD/
      DOUBLE PRECISION Y/8HABCDEFGH/
      CHARACTER*10 C/'QRSTUVWXYZ'/
      READ (C,'(A4,A6)') R, S
      WRITE (6,100) D, E, E(2), X, Y, R, R, S
  100 FORMAT (1X,'>HOLTEXT ',A1,A1,A4,A2,1X,A4,1X,A8,1X,A4,1X,A6,1X,A4)
      END
