C     PLIST -- PARAMETER LISTS AS FORTRAN H BUILDS THEM (ISSUE #18):
C     ASSEMBLED ONCE IN THE STATIC AREA, AN ADDRESS THE LINKAGE EDITOR
C     FIXES (A LOCAL, A COMMON MEMBER, A CONSTANT, A PROCEDURE) A WORD
C     THERE, ONLY ONE KNOWN AT RUN TIME (A DUMMY PASSED ON, AN ELEMENT
C     AT A COMPUTED SUBSCRIPT) STORED AT THE CALL; THE RUNTIME'S LISTS
C     THE SAME, A CONSTANT VALUE A WORD THERE.  LISTS OF THE SAME TEXT
C     ARE ONE LIST, AND A WORD STORED AT ONE CALL MUST NOT BE TAKEN FOR
C     A CONSTANT AT ANOTHER: A WRITE OF A VARIABLE KNOWN TO BE 0, AFTER
C     ONE OF A VARIABLE, PRINTED THE VARIABLE (FCVS FM007'S COUNTS).
C     SELF-CHECKING: ONE LINE A CASE, " >NAME OK" OR " >NAME BAD", THEN
C     THE COUNT OF BAD ONES.
      PROGRAM PLIST
      COMMON /PLC/ C(10), KC
      INTEGER NBAD, K, KZ, I, KA(5), ISUM
      REAL A(5), R, ADDR
      CHARACTER*4 B1, B2, B3
      EXTERNAL ADDR
      NBAD = 0
      KC = 0
      DO 10 I = 1, 10
        C(I) = REAL(I)
   10 CONTINUE
      DO 20 I = 1, 5
        A(I) = REAL(10 * I)
        KA(I) = I
   20 CONTINUE
C     CONSTANT ADDRESSES: A LOCAL, AN ELEMENT, A COMMON MEMBER, A
C     CONSTANT, A TEMPORARY, A PROCEDURE; TWICE, ONE LIST
      R = 0.0
      CALL SUM5(R, A(2), C(3), 4.0, R + 1.0, ADDR)
      CALL CHK('CONST ', R .EQ. 20.0 + 3.0 + 4.0 + 1.0 + 7.0, NBAD)
      CALL SUM5(R, A(2), C(3), 4.0, R + 1.0, ADDR)
      CALL CHK('AGAIN ', R .EQ. 35.0 + 20.0 + 3.0 + 4.0 + 36.0 + 7.0,
     1    NBAD)
C     RUN-TIME ADDRESSES: A COMPUTED SUBSCRIPT, A DUMMY PASSED ON
      ISUM = 0
      DO 30 I = 1, 5
        CALL ADDK(ISUM, KA(I))
   30 CONTINUE
      CALL CHK('SUBSCR', ISUM .EQ. 15, NBAD)
      ISUM = 0
      CALL PASSON(ISUM, KA(3))
      CALL CHK('DUMMY ', ISUM .EQ. 3 .AND. KC .EQ. 3, NBAD)
C     THE RUNTIME'S LISTS: A VARIABLE, THEN ONE KNOWN TO BE 0, THEN
C     THE CONSTANT 0, EACH TO ITS OWN BUFFER
      K = 7
      KZ = 0
      WRITE (B1, 40) K
      WRITE (B2, 40) KZ
      WRITE (B3, 40) 0
   40 FORMAT(I4)
      CALL CHK('WRITE ', B1 .EQ. '   7' .AND. B2 .EQ. '   0' .AND.
     1    B3 .EQ. '   0', NBAD)
C     A REAL WIDENED FOR THE C LIBRARY: ITS ZERO WORD IS THE LIST'S
      R = 0.25
      CALL CHK('WIDEN ', ABS(SQRT(R) - 0.5) .LT. 1.0E-6 .AND.
     1    ABS(EXP(R + R) - 1.6487213) .LT. 1.0E-6, NBAD)
      WRITE (6,1) NBAD
    1 FORMAT(' >BAD ', I2)
      END
      SUBROUTINE SUM5(R, X, Y, Z, W, F)
      REAL R, X, Y, Z, W, F
      R = R + X + Y + Z + W + F(3.0)
      END
      REAL FUNCTION ADDR(X)
      REAL X
      ADDR = X + 4.0
      END
      SUBROUTINE ADDK(ISUM, K)
      INTEGER ISUM, K
      ISUM = ISUM + K
      END
      SUBROUTINE PASSON(ISUM, K)
      COMMON /PLC/ C(10), KC
      INTEGER ISUM, K
      CALL ADDK(ISUM, K)
      CALL ADDK(KC, K)
      END
      SUBROUTINE CHK(NAME, OK, NBAD)
      CHARACTER*6 NAME
      LOGICAL OK
      INTEGER NBAD
      IF (OK) THEN
        WRITE (6,1) NAME
    1   FORMAT(' >', A6, ' OK')
      ELSE
        WRITE (6,2) NAME
    2   FORMAT(' >', A6, ' BAD')
        NBAD = NBAD + 1
      END IF
      END
