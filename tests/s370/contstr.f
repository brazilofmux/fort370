C     A CHARACTER OR HOLLERITH CONSTANT CONTINUED FROM A LINE THAT ENDS
C     SHORT OF COLUMN 72.  THE LINE IS BLANK OUT TO 72, AS ITS CARD WAS,
C     AND THE BLANKS BELONG TO THE CONSTANT.  THE HOST COMPILER HAD
C     JOINED THE CONTINUATION RIGHT AFTER THE LAST CHARACTER, SO A HOST
C     FILE WITH TRIMMED LINES COMPILED DIFFERENTLY FROM THE SAME DECK ON
C     MVS.  'AB' ENDS IN COLUMN 13, SO 59 BLANKS FOLLOW AND 'CD' STARTS
C     AT POSITION 62.  'XY' ENDS IN COLUMN 22, SO THE HOLLERITH COUNT 53
C     TAKES 'XY', 50 BLANKS AND 'Z', AND THE MARKER FOLLOWS THE Z.
      CHARACTER*80 S
      S = 'AB
     1CD'
      WRITE (6,100) INDEX(S,'CD')
  100 FORMAT (1X,'>CONTSTR',I4)
      WRITE (6,200)
  200 FORMAT (1X,53HXY
     1Z,'<')
      END
