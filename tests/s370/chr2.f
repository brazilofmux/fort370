C     FCVS FM301 TEST 18: AN IMPLICIT CHARACTER*2 (F) RULE, THEN AN
C     EXPLICIT CHARACTER FVTN01*3 -- THE DECLARATION WINS
      IMPLICIT CHARACTER*14 (C)
      IMPLICIT CHARACTER*2 (F)
      CHARACTER FVTN01*3
      CVCOMP = '   '
      FVTN01 = 'ABC'
      CVCORR = 'ABC'
      CVCOMP = FVTN01
      IF (CVCOMP .EQ. 'ABC') WRITE(6,100) 'EQ'
      IF (CVCOMP .NE. 'ABC') WRITE(6,100) 'NE'
      WRITE(6,101) CVCOMP, FVTN01, CVCORR
  100 FORMAT(' >',A2)
  101 FORMAT(' >',A14,'#',A3,'#',A14,'#')
      STOP
      END
