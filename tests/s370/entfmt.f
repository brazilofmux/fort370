C     ENTFMT -- A SUBROUTINE WITH AN ENTRY POINT, COMPILED FROM ITS
C     WHOLE TEXT FOR THE ENTRY, FINDS ITS OWN FORMATS, AN ASSIGNED
C     FORMAT AMONG THEM, AND A READ INTO A DOUBLE PRECISION LOCAL, ONCE
C     AND IN A LOOP: THE TABLES OF THE TEXT ARE THE PARENT'S.  BEFORE,
C     EVERY ONE OF ITS FORMATS WAS "NO FORMAT STATEMENT WITH THAT LABEL"
C     WHEN THE ENTRY WAS COMPILED.  UNIT 21 IS A SCRATCH DD.  EXPECTED
C     (FORTRAN H PRINTS THE SAME WITH WRITE (6,2) N; IT HAS NO ASSIGNED
C     FORMATS):
C     >E2    3
C     >D   2.5000
C     >Y   7.5000
C     >S1    4
      CALL E2(3)
      CALL S1(4)
      STOP
      END
      SUBROUTINE S1(N)
      DOUBLE PRECISION D, Y
      WRITE (6,1) N
    1 FORMAT(' >S1 ', I4)
      RETURN
      ENTRY E2(N)
      ASSIGN 2 TO K
      WRITE (6,K) N
    2 FORMAT(' >E2 ', I4)
      D = 2.5D0
      WRITE (21) D
      REWIND 21
      D = 0.0D0
      READ (21) D
      WRITE (6,4) D
    4 FORMAT(' >D ', F8.4)
C     THE READ IN A LOOP, D LIVE ACROSS IT.  WHERE A DOUBLE IS TWO WORDS
C     (THE SLOW-32 BACK END), THE ENTRY'S MISSED ESCAPE SPLIT THEM AND THE
C     LOOP LOST THE READ'S VALUE; ON S/370 A DOUBLE IS ONE REGISTER, AND
C     THIS ONLY CHECKS THE LOOP.
      Y = 0.0D0
      DO 5 I = 1, 3
        READ (21) D
        REWIND 21
        Y = Y + D
    5 CONTINUE
      WRITE (6,6) Y
    6 FORMAT(' >Y ', F8.4)
      RETURN
      END
