C     HYPX -- DSINH, DCOSH AND DTANH AT 100,000 ARGUMENTS EACH, THE
C     BITS OF THEIR RESULTS FOLDED INTO A HASH (ISSUE #3): THE ONES IN
C     ASSEMBLER DO THE SAME FLOATING-POINT OPERATIONS IN THE SAME ORDER
C     AS THE ONES IN C, SO THEY GIVE THE SAME HASHES.  THE ARGUMENTS ARE
C     OF EITHER SIGN AND RANDOM IN MAGNITUDE FROM 1E-6 TO 174 ON A LOG
C     SCALE (XORSHIFT32): EVERY BRANCH, THE SERIES BELOW 1/8 AND 1/4096,
C     THE CORRECTED RECIPROCAL BELOW 0.8814, DTANH'S TWO FORMS EITHER
C     SIDE OF 1.75 AND ITS 1 PAST 22.  AND A FEW WHOSE VALUES ARE KNOWN,
C     AND PAST 175.366 (THE C ENTRIES: FORTLIB'S MESSAGE, AND THE
C     LARGEST POSITIVE NUMBER).  SELF-CHECKING FOR THOSE: " >NAME OK" OR
C     " >NAME BAD"; THE HASHES ARE PRINTED, " >HASHN" AND THE VALUE.
      PROGRAM HYPX
      DOUBLE PRECISION X, Y, T
      INTEGER IX(2), IY(2), IS, IH, I, K, NBAD
      EQUIVALENCE (X, IX(1)), (Y, IY(1))
      NBAD = 0
      CALL CHK('SINH0  ', DSINH(0.0D0) .EQ. 0.0D0, NBAD)
      CALL CHK('COSH0  ', DCOSH(0.0D0) .EQ. 1.0D0, NBAD)
      CALL CHK('TANH0  ', DTANH(0.0D0) .EQ. 0.0D0, NBAD)
      CALL CHK('TANH30 ', DTANH(-30.0D0) .EQ. -1.0D0, NBAD)
      CALL CHK('SINH1  ', DABS(DSINH(1.0D0) - 1.1752011936438014D0)
     1    .LT. 1.0D-15, NBAD)
      CALL CHK('COSH1  ', DABS(DCOSH(1.0D0) - 1.5430806348152437D0)
     1    .LT. 1.0D-15, NBAD)
      CALL CHK('TANH1  ', DABS(DTANH(1.0D0) - 0.76159415595576488D0)
     1    .LT. 1.0D-15, NBAD)
C     FORTLIB'S FIXUP: THE LARGEST POSITIVE NUMBER, OF EITHER SIGN
      CALL CHK('SINHBIG', DSINH(-200.0D0) .GT. 7.0D75, NBAD)
      CALL CHK('COSHBIG', DCOSH(200.0D0) .GT. 7.0D75, NBAD)
      IS = 12345
      DO 30 K = 1, 3
        IH = 0
        DO 10 I = 1, 100000
          CALL XSH(IS)
          T = DBLE(IAND(IS, 2147483647)) / 2147483648.0D0
          X = 10.0D0 ** (-6.0D0 + 8.24D0 * T)
          IF (IS .LT. 0) X = -X
          IF (K .EQ. 1) Y = DSINH(X)
          IF (K .EQ. 2) Y = DCOSH(X)
          IF (K .EQ. 3) Y = DTANH(X)
          IH = IEOR(ISHFTC(IH, 5, 32), IY(1))
          IH = IEOR(ISHFTC(IH, 7, 32), IY(2))
   10   CONTINUE
        WRITE (6,1) K, IH
    1   FORMAT(' >HASH', I1, 1X, Z8)
   30 CONTINUE
      WRITE (6,2) NBAD
    2 FORMAT(' >BAD ', I2)
      END
      SUBROUTINE XSH(IS)
      INTEGER IS
      IS = IEOR(IS, ISHFT(IS, 13))
      IS = IEOR(IS, ISHFT(IS, -17))
      IS = IEOR(IS, ISHFT(IS, 5))
      END
      SUBROUTINE CHK(NAME, OK, NBAD)
      CHARACTER*7 NAME
      LOGICAL OK
      INTEGER NBAD
      IF (OK) THEN
        WRITE (6,1) NAME
    1   FORMAT(' >', A7, ' OK')
      ELSE
        WRITE (6,2) NAME
    2   FORMAT(' >', A7, ' BAD')
        NBAD = NBAD + 1
      END IF
      END
