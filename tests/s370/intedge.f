C     INTEDGE -- THE EDGES OF THE NUMBERS (ISSUE #20).  A DO LOOP TO
C     2147483647 RUNS ITS 8 TRIPS (F77 11.10.3: AN ITERATION COUNT;
C     A BXLE'S ADD WRAPPED, AND THE LOOP NEVER ENDED); -2**31 / -1
C     FOLDS TO -2**31, IN A STATEMENT AND IN A PARAMETER, AS FORTRAN H
C     FOLDS IT (THE COMPILER'S OWN DIVISION TRAPPED ON MVS, S0C9); AND
C     A DOUBLE PRECISION NUMBER BELOW 1E-77 WITH 17 DIGITS, AS A
C     CONSTANT AND READ, IS ITSELF, NOT ZERO.  SELF-CHECKING: ONE LINE
C     A CASE, " >NAME OK" OR " >NAME BAD", THEN THE COUNT OF BAD ONES.
      PROGRAM INTEDG
      INTEGER I, N, LAST, NEG, J, NBAD, IP
      INTEGER ID(2), IE(2), IS(2)
      DOUBLE PRECISION D, E, S
      CHARACTER*25 T
      PARAMETER (IP = (-2147483647 - 1) / (-1))
      EQUIVALENCE (D, ID(1)), (E, IE(1)), (S, IS(1))
      DATA IS /Z011286D8, Z0EC190DB/
      NBAD = 0
      N = 0
      LAST = 0
      DO 10 I = 2147483640, 2147483647
        N = N + 1
        LAST = I
   10 CONTINUE
      CALL CHK('DOTOP ', N .EQ. 8 .AND. LAST .EQ. 2147483647, NBAD)
      NEG = -2147483647 - 1
      J = (-2147483647 - 1) / (-1)
      CALL CHK('DIVM1 ', J .EQ. NEG, NBAD)
      CALL CHK('PARM1 ', IP .EQ. NEG, NBAD)
      D = 9.9999999999999974D-78
      CALL CHK('DTINY ', ID(1) .EQ. IS(1) .AND. ID(2) .EQ. IS(2), NBAD)
      T = '  9.9999999999999974D-78'
      READ (T, '(D25.0)') E
      CALL CHK('RTINY ', IE(1) .EQ. IS(1) .AND. IE(2) .EQ. IS(2), NBAD)
      WRITE (6,1) NBAD
    1 FORMAT(' >BAD ', I2)
      END
      SUBROUTINE CHK(NAME, OK, NBAD)
      CHARACTER*6 NAME
      LOGICAL OK
      INTEGER NBAD
      IF (OK) THEN
        WRITE (6,1) NAME
    1   FORMAT(' >', A6, ' OK')
      ELSE
        WRITE (6,2) NAME
    2   FORMAT(' >', A6, ' BAD')
        NBAD = NBAD + 1
      END IF
      END
