C     INITIAL VALUES IN A TYPE STATEMENT, IBM'S EXTENSION (FORTRAN IV
C     AND VS FORTRAN): THE SAME AS DATA FOR THE WHOLE ENTITY, REPEAT
C     COUNTS INCLUDED.  THE COMPILER HAD SKIPPED THEM, AND WITH THEM
C     EVERY NAME AFTER THEM IN THE STATEMENT -- K WAS UNDEFINED AND
C     ARR LOST ITS DIMENSION, SO ARR(1)=... READ AS A STATEMENT
C     FUNCTION.  GFORTRAN PRINTS THE SAME LINE.
      INTEGER K/12345/, ARR(3)/1,2*7/, M
      CHARACTER*4 C/'ABCD'/
      REAL X(2)/1.5,2.5/
      ARR(1)=ARR(1)+0
      M=1
      WRITE(6,10) K, ARR, M, C, X
10    FORMAT(1X,'>TYPEINIT',I6,3I3,I2,1X,A4,2F5.1)
      END
