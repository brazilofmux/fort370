C     CXARG -- SPECIFIC INTRINSICS AS ACTUAL ARGUMENTS (F77 15.9.3):
C     THE COMPLEX ONES, CSQRT CEXP CLOG CSIN CCOS CONJG CABS AIMAG, AND
C     COMPLEX*16'S CDSQRT CDEXP CDLOG CDSIN CDCOS DCONJG CDABS DIMAG,
C     NAMED IN INTRINSIC AND CALLED THROUGH A DUMMY PROCEDURE, MUST GIVE
C     WHAT A DIRECT CALL GIVES, TO THE BIT; AND FORTRAN IV'S WAY, A
C     LIBRARY FUNCTION NAMED IN EXTERNAL (SQRT, SIN, CSQRT), PASSED AND
C     CALLED, AS FORTRAN H DOES IT; AND THE REAL ONES, SQRT TO TANH, AT
C     TEN ARGUMENTS EACH (A REAL FUNCTION'S LONG RESULT IS CUT TO SHORT,
C     THROUGH A DUMMY AS IN A DIRECT CALL).  SELF-CHECKING: ONE LINE A NAME,
C     " >NAME OK" OR " >NAME BAD", THEN THE COUNT OF BAD ONES.
      INTRINSIC CSQRT, CEXP, CLOG, CSIN, CCOS, CONJG, CABS, AIMAG
      INTRINSIC CDSQRT, CDEXP, CDLOG, CDSIN, CDCOS, DCONJG, CDABS, DIMAG
      COMPLEX C, CAPPLY
      DOUBLE COMPLEX Z, ZAPPLY
      DOUBLE PRECISION DAPPLY
      INTEGER NBAD
      C = (0.5, 1.25)
      Z = DCMPLX(0.5D0, 1.25D0)
      NBAD = 0
      CALL CHK('CSQRT ', CAPPLY(CSQRT, C) .EQ. CSQRT(C), NBAD)
      CALL CHK('CEXP  ', CAPPLY(CEXP, C) .EQ. CEXP(C), NBAD)
      CALL CHK('CLOG  ', CAPPLY(CLOG, C) .EQ. CLOG(C), NBAD)
      CALL CHK('CSIN  ', CAPPLY(CSIN, C) .EQ. CSIN(C), NBAD)
      CALL CHK('CCOS  ', CAPPLY(CCOS, C) .EQ. CCOS(C), NBAD)
      CALL CHK('CONJG ', CAPPLY(CONJG, C) .EQ. CONJG(C), NBAD)
      CALL CHK('CABS  ', RAPPLY(CABS, C) .EQ. CABS(C), NBAD)
      CALL CHK('AIMAG ', RAPPLY(AIMAG, C) .EQ. AIMAG(C), NBAD)
      CALL CHK('CDSQRT', ZAPPLY(CDSQRT, Z) .EQ. CDSQRT(Z), NBAD)
      CALL CHK('CDEXP ', ZAPPLY(CDEXP, Z) .EQ. CDEXP(Z), NBAD)
      CALL CHK('CDLOG ', ZAPPLY(CDLOG, Z) .EQ. CDLOG(Z), NBAD)
      CALL CHK('CDSIN ', ZAPPLY(CDSIN, Z) .EQ. CDSIN(Z), NBAD)
      CALL CHK('CDCOS ', ZAPPLY(CDCOS, Z) .EQ. CDCOS(Z), NBAD)
      CALL CHK('DCONJG', ZAPPLY(DCONJG, Z) .EQ. DCONJG(Z), NBAD)
      CALL CHK('CDABS ', DAPPLY(CDABS, Z) .EQ. CDABS(Z), NBAD)
      CALL CHK('DIMAG ', DAPPLY(DIMAG, Z) .EQ. DIMAG(Z), NBAD)
      CALL REALS(NBAD)
      CALL OLDWAY(NBAD)
      WRITE (6,1) NBAD
    1 FORMAT(' >BAD ', I2)
      END
C     THE REAL ONES, AT TEN ARGUMENTS IN (0, 1)
      SUBROUTINE REALS(NBAD)
      INTRINSIC SQRT, EXP, ALOG, ALOG10, SIN, COS, TAN, ASIN, ACOS
      INTRINSIC ATAN, SINH, COSH, TANH
      INTEGER NBAD, I, K(13)
      REAL X
      DO 10 I = 1, 13
        K(I) = 0
   10 CONTINUE
      DO 20 I = 1, 10
        X = 0.0937 * REAL(I)
        IF (RAPPLY1(SQRT, X) .NE. SQRT(X)) K(1) = K(1) + 1
        IF (RAPPLY1(EXP, X) .NE. EXP(X)) K(2) = K(2) + 1
        IF (RAPPLY1(ALOG, X) .NE. ALOG(X)) K(3) = K(3) + 1
        IF (RAPPLY1(ALOG10, X) .NE. ALOG10(X)) K(4) = K(4) + 1
        IF (RAPPLY1(SIN, X) .NE. SIN(X)) K(5) = K(5) + 1
        IF (RAPPLY1(COS, X) .NE. COS(X)) K(6) = K(6) + 1
        IF (RAPPLY1(TAN, X) .NE. TAN(X)) K(7) = K(7) + 1
        IF (RAPPLY1(ASIN, X) .NE. ASIN(X)) K(8) = K(8) + 1
        IF (RAPPLY1(ACOS, X) .NE. ACOS(X)) K(9) = K(9) + 1
        IF (RAPPLY1(ATAN, X) .NE. ATAN(X)) K(10) = K(10) + 1
        IF (RAPPLY1(SINH, X) .NE. SINH(X)) K(11) = K(11) + 1
        IF (RAPPLY1(COSH, X) .NE. COSH(X)) K(12) = K(12) + 1
        IF (RAPPLY1(TANH, X) .NE. TANH(X)) K(13) = K(13) + 1
   20 CONTINUE
      CALL CHK('SQRT  ', K(1) .EQ. 0, NBAD)
      CALL CHK('EXP   ', K(2) .EQ. 0, NBAD)
      CALL CHK('ALOG  ', K(3) .EQ. 0, NBAD)
      CALL CHK('ALOG10', K(4) .EQ. 0, NBAD)
      CALL CHK('SIN   ', K(5) .EQ. 0, NBAD)
      CALL CHK('COS   ', K(6) .EQ. 0, NBAD)
      CALL CHK('TAN   ', K(7) .EQ. 0, NBAD)
      CALL CHK('ASIN  ', K(8) .EQ. 0, NBAD)
      CALL CHK('ACOS  ', K(9) .EQ. 0, NBAD)
      CALL CHK('ATAN  ', K(10) .EQ. 0, NBAD)
      CALL CHK('SINH  ', K(11) .EQ. 0, NBAD)
      CALL CHK('COSH  ', K(12) .EQ. 0, NBAD)
      CALL CHK('TANH  ', K(13) .EQ. 0, NBAD)
      RETURN
      END
C     FORTRAN IV'S WAY: THE LIBRARY'S FUNCTIONS NAMED IN EXTERNAL
      SUBROUTINE OLDWAY(NBAD)
      EXTERNAL SQRT, SIN, CSQRT
      COMPLEX C, CAPPLY, CSQRT
      INTEGER NBAD
      C = (0.5, 1.25)
      CALL CHK('XSQRT ', RAPPLY1(SQRT, 2.0) .EQ. SQRT(2.0) .AND.
     1     ABS(SQRT(2.0) - 1.4142135) .LT. 1.0E-6, NBAD)
      CALL CHK('XSIN  ', RAPPLY1(SIN, 0.5) .EQ. SIN(0.5) .AND.
     1     ABS(SIN(0.5) - 0.47942553) .LT. 1.0E-6, NBAD)
      CALL CHK('XCSQRT', CAPPLY(CSQRT, C) .EQ. CSQRT(C) .AND.
     1     ABS(REAL(CSQRT(C)) - 0.9608047) .LT. 1.0E-6, NBAD)
      RETURN
      END
      COMPLEX FUNCTION CAPPLY(F, Z)
      COMPLEX F, Z
      EXTERNAL F
      CAPPLY = F(Z)
      END
      DOUBLE COMPLEX FUNCTION ZAPPLY(F, Z)
      DOUBLE COMPLEX F, Z
      EXTERNAL F
      ZAPPLY = F(Z)
      END
      REAL FUNCTION RAPPLY(F, Z)
      COMPLEX Z
      EXTERNAL F
      RAPPLY = F(Z)
      END
      REAL FUNCTION RAPPLY1(F, X)
      EXTERNAL F
      RAPPLY1 = F(X)
      END
      DOUBLE PRECISION FUNCTION DAPPLY(F, Z)
      DOUBLE COMPLEX Z
      DOUBLE PRECISION F
      EXTERNAL F
      DAPPLY = F(Z)
      END
      SUBROUTINE CHK(NAME, OK, NBAD)
      CHARACTER*6 NAME
      LOGICAL OK
      INTEGER NBAD
      IF (OK) THEN
        WRITE (6,1) NAME
    1   FORMAT(' >', A6, ' OK')
      ELSE
        WRITE (6,2) NAME
    2   FORMAT(' >', A6, ' BAD')
        NBAD = NBAD + 1
      END IF
      END
