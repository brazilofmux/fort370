C     PROGRAM STATEMENT.  THE UNIT SCAN HAD STARTED A MAIN PROGRAM ONLY
C     BEFORE THE FIRST SUBPROGRAM, SO ONE AFTER THEM WAS TAKEN FOR MORE
C     OF THE LAST SUBPROGRAM, PAST ITS END, AND NEVER COMPILED.
