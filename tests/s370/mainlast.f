      END
      INTEGER FUNCTION INC(I)
      INC = I + 1
      END
      SUBROUTINE PRINTIT(N)
      WRITE(6,100) N
100   FORMAT(1X,'>MAINLAST ',I3)
      RETURN
      END
200   FORMAT(1X,'>MAINLAST OK')
      COMMON /C/ K
      CALL PRINTIT(INC(K))
      WRITE(6,200)
      STOP
      END
