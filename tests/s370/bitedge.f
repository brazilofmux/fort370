C     BITEDGE -- THE BIT FUNCTIONS AT THEIR EDGES (MIL-STD-1753 2.6): A
C     SHIFT BY 32 EITHER WAY GIVES 0, AND A FIELD OF LENGTH 0 IS EMPTY
C     (IBITS GIVES 0, MVBITS MOVES NOTHING) -- WITH THE COUNTS CONSTANT,
C     IN VARIABLES THE COMPILER CAN SEE THROUGH, AND READ AT RUN TIME.
C     A SHIFT OF 32 IS WHERE THE HOST'S C (A COUNT TAKEN MOD 32) AND THE
C     MACHINE (MOD 64) PART: FOLDED, ISHFT(K, 32) WAS K.  EACH CASE ON
C     ITS OWN LINE: " >NAME OK" OR " >NAME BAD", THEN THE COUNT.
      INTEGER K, N, M, L, LZ, J, NBAD, NR(2)
      CHARACTER*8 C
      K = 12345
      N = 32
      M = -32
      L = 0
      NBAD = 0
      C = '  32  00'
      READ (C, '(2I4)') NR
      LZ = NR(2)
      CALL CHK('SHC+32', ISHFT(K, 32) .EQ. 0, NBAD)
      CALL CHK('SHC-32', ISHFT(K, -32) .EQ. 0, NBAD)
      CALL CHK('SHV+32', ISHFT(K, N) .EQ. 0, NBAD)
      CALL CHK('SHV-32', ISHFT(K, M) .EQ. 0, NBAD)
      CALL CHK('SHR+32', ISHFT(K, NR(1)) .EQ. 0, NBAD)
      CALL CHK('SHR-32', ISHFT(K, -NR(1)) .EQ. 0, NBAD)
      CALL CHK('IBITSC', IBITS(K, 3, 0) .EQ. 0, NBAD)
      CALL CHK('IBITSV', IBITS(K, 3, L) .EQ. 0, NBAD)
      CALL CHK('IBITSR', IBITS(K, 3, LZ) .EQ. 0, NBAD)
      J = 7
      CALL MVBITS(K, 0, 0, J, 2)
      CALL CHK('MVBITC', J .EQ. 7, NBAD)
      J = 7
      CALL MVBITS(K, 0, L, J, 2)
      CALL CHK('MVBITV', J .EQ. 7, NBAD)
      J = 7
      CALL MVBITS(K, 0, LZ, J, 2)
      CALL CHK('MVBITR', J .EQ. 7, NBAD)
      WRITE (6,1) NBAD
    1 FORMAT(' >BAD ', I2)
      END
      SUBROUTINE CHK(NAME, OK, NBAD)
      CHARACTER*6 NAME
      LOGICAL OK
      INTEGER NBAD
      IF (OK) THEN
        WRITE (6,1) NAME
    1   FORMAT(' >', A6, ' OK')
      ELSE
        WRITE (6,2) NAME
    2   FORMAT(' >', A6, ' BAD')
        NBAD = NBAD + 1
      END IF
      END
