C     A DO LOOP WHOSE INDEX IS SPILLED.  THE BXLE/BXH LOOP TEST COPIED
C     THE INDEX FROM ITS REGISTER, AND A SPILLED INDEX HAS NONE: THE
C     ASSEMBLER GOT "LR 2,/", WHICH IFOX00 REJECTS.  NOW SUCH A LOOP
C     TESTS WITH AN ADD, A COMPARE AND A BRANCH.  CUT DOWN MECHANICALLY
C     FROM A 1985 STATISTICS PROGRAM AND RENAMED, KEEPING EACH NAME'S
C     TYPE; THE REGISTER PRESSURE, NOT THE ARITHMETIC, IS THE TEST.  IT
C     IS COMPILED, NOT RUN.
      SUBROUTINE BXSPIL  (I01,X01,I02,X02,I03,X03,I04,X04,X05,I05,I06,
     1   I07,I08,I09,I10,I11,I12,I13,I14,I15,I16,I17,X06,I18,I19)
      INTEGER  I05(10,8),I20(16),I02(I11),I03(I11),X07
      REAL X04(I12,I12),X01(I12),X02(I11),X03(I11),X08
      DO  600   I21=1,I08
  600 WRITE(I18) I22,X09,(X03(I23),I23=1,I11)
      IF(X09.LE.0..OR.I21.GT.I09)  GOTO  602
      DO  533 I23=1,I11
      DO  533 I24=1,I23
  533 X04(I23,I24)=X04(I23,I24)+X03(I23)*X03(I24)/X09
      IF  (I17 .EQ. 0)  GO TO 330
      I25  =  -X10 - SIGN(0.5,X10)
  330 I26=19
      I27=(I11-1)/I26+1
      DO 200  I24=1,I27
      I28=I24*I26
      IF  (I17 .NE. 0)  WRITE  (I29,39)  I25
   39 FORMAT  (' ',I5)
  210 I02(I23)  =  X01(I23) * 10.**I30 + 0.5
      DO 201 I21=1,I08
      READ(I18)I22,X09,(X03(I23),I23=1,I11)
      DO  211  I23=I31,I28
  211 I02(I23)  =  X03(I23) * 10.**I25 + 0.5
  201 WRITE(I29,28) I22,(I02(I23),I23=I31,I28),IPI
  200 CONTINUE
  602 CONTINUE
   28 FORMAT(' ',A4,3X,' !',20I6)
      END
