C     ZCHK -- THE COMPLEX AND COMPLEX*16 FUNCTIONS' ARGUMENTS OUT OF
C     THEIR DOMAINS, AS FORTLIB TREATS THEM (ISSUE #30): EACH GETS ITS
C     IHC MESSAGE, AS FORTRAN H'S (IHC246I-247I, IHC271I-275I,
C     IHC281I-285I), AND ITS FIXUP; AND THE LIMITS FORTLIB TESTS, JUST
C     BELOW AND AT EACH, WITH THE REAL AND DOUBLE PRECISION ONES'
C     (IHC252I, 254I, 256I, 262I, 264I, 266I), AS H TESTS THEM: EXP'S
C     174.673 IS X'42AEAC50', DEXP'S X'42AEAC4F00000000'; SIN'S PI*2**18
C     X'45C90FDA', BUT CSIN'S AND CEXP'S X'45C90000'; DSIN'S PI*2**50
C     X'4DC90FDA00000000'.  A CDEXP OR CDSIN BETWEEN DEXP'S LIMIT AND
C     ITS OWN TAKES DEXP'S MESSAGE.  EACH RESULT IN HEXADECIMAL.  THE
C     EXPECTED LINES, AND H'S WHERE THEY DIFFER: THE FIXUPS ARE THE
C     LARGEST NUMBER, OR HALF OF IT, TIMES A SINE OR COSINE, FORTLIB'S A
C     FEW UNITS FROM OURS; THE REST ARE COMPUTED, OURS WITHIN A UNIT OF
C     THE EXACT VALUE (CQ1, CS2, CE4, CA1, R3), H'S UP TO 11 UNITS
C     AWAY; ZE6, AN ARGUMENT OF 3.5E15, H'S IN ITS THIRD DIGIT.
C       >CE1 7F8A513F 7FD76AA3
C       >CE2 7FFFFF68 00000000
C       >CE3 7FFFFFFF 00000000
C       >CE4 4125E837 41155292
C          H: 4125E836 41155292
C       >CE5 00000000 00000000
C       >CE6 00000000 00000000
C       >CL1 FFFFFFFF 00000000
C       >CS1 00000000 00000000
C       >CS2 40C1AA78 41106372
C          H: 40C1AA6C 41106371
C       >CS3 7F6BB551 7F45289F
C       >CS4 7F7463DA 7F35444C
C          H: 7F7463DA 7F35444B
C       >CS5 7F6BB512 7F452877
C          H: 7F6BB512 7F452876
C       >CS6 00000000 00000000
C       >CC1 7F45289F FF6BB551
C       >CC2 FF35444C FF7463DA
C          H: FF35444B FF7463DA
C       >CQ1 5FAD3A53 601A2358
C          H: 5FAD3A50 601A2357
C       >CA1 7FB0DE65
C          H: 7FB0DE64
C       >CP1 00000000 00000000
C       >CP2 00000000 00000000
C       >ZE1 7F8A51407DA8345B 7FD76AA478486771
C          H: 7F8A51407DA83462 7FD76AA47848676D
C       >ZE2 7FFFFF680DA4DB33 0000000000000000
C          H: 7FFFFF680DA4DB34 0000000000000000
C       >ZE3 7FFFFFFFFFFFFFFF 0000000000000000
C       >ZE4 7FFFFFFFFFFFFFFF 0000000000000000
C       >ZE5 0000000000000000 0000000000000000
C       >ZE6 41208FDF5CA31070 C11CD5203BDD3D6D
C          H: 412039CF949C7D04 C11D3531560ADDD5
C       >ZL1 FFFFFFFFFFFFFFFF 0000000000000000
C       >ZS1 0000000000000000 0000000000000000
C       >ZS2 7F6BB5523C2433B8 7F4528A03ED41A2D
C          H: 7F6BB5523C2433B6 7F4528A03ED41A30
C       >ZS3 7F6BB5523C2433B8 FF4528A03ED41A2D
C          H: 7F6BB5523C2433B6 FF4528A03ED41A30
C       >ZS4 7F6BB5523C2433B8 7F4528A03ED41A2D
C          H: 7F6BB5523C2433B6 7F4528A03ED41A30
C       >ZC1 FF35444CAEA6E408 FF7463DBAB46D117
C          H: FF35444CAEA6E407 FF7463DBAB46D118
C       >ZP1 0000000000000000 0000000000000000
C       >R1 7FFFFF68
C       >R2 7FFFFFFF
C       >R3 7FFFFE50
C          H: 7FFFFE51
C       >R4 7FFFFFFF
C       >R5 40B504F3
C       >D1 7FFFFF680DA4DB33
C          H: 7FFFFF680DA4DB34
C       >D2 7FFFFFFFFFFFFFFF
C       >D3 7FFFFFFFFFFFFFFF
C       >D4 40B504F333F9DE70
      PROGRAM ZCHK
      COMPLEX C, W
      COMPLEX*16 Z, V
      DOUBLE PRECISION D(6), E
      REAL A(6)
      INTEGER IW(2), IV(4), IA(6), ID(12), IE(2)
      EQUIVALENCE (W, IW(1)), (V, IV(1)), (A(1), IA(1)), (D(1), ID(1))
      EQUIVALENCE (X, IX), (E, IE(1))
C     BELOW AND AT EXP'S LIMIT, SINH'S, AND SIN'S (COMPLEX'S, REAL'S)
      DATA IA /Z42AEAC4F, Z42AEAC50, Z42AF5DC0, Z42AF5DC1, Z45C90000,
     1   Z45C90FDA/
C     DEXP'S, BELOW AND AT; CDEXP'S; DSINH'S; DSIN'S, AT AND BELOW
      DATA ID /Z42AEAC4E, ZFFFFFFFF, Z42AEAC4F, Z00000000,
     1   Z42AEAC50, Z00000000, Z42AF5DC1, Z00000000, Z4DC90FDA,
     2   Z00000000, Z4DC90FD9, ZFFFFFFFF/
      C = CMPLX(200.0, 1.0)
      W = CEXP(C)
      WRITE (6,101) IW
  101 FORMAT(' >CE1 ', Z8, 1X, Z8)
      C = CMPLX(A(1), 0.0)
      W = CEXP(C)
      WRITE (6,102) IW
  102 FORMAT(' >CE2 ', Z8, 1X, Z8)
      C = CMPLX(A(2), 0.0)
      W = CEXP(C)
      WRITE (6,103) IW
  103 FORMAT(' >CE3 ', Z8, 1X, Z8)
      C = CMPLX(1.0, 823280.0)
      W = CEXP(C)
      WRITE (6,104) IW
  104 FORMAT(' >CE4 ', Z8, 1X, Z8)
      C = CMPLX(1.0, A(5))
      W = CEXP(C)
      WRITE (6,105) IW
  105 FORMAT(' >CE5 ', Z8, 1X, Z8)
      C = CMPLX(200.0, 1.0E6)
      W = CEXP(C)
      WRITE (6,106) IW
  106 FORMAT(' >CE6 ', Z8, 1X, Z8)
      C = CMPLX(0.0, 0.0)
      W = CLOG(C)
      WRITE (6,107) IW
  107 FORMAT(' >CL1 ', Z8, 1X, Z8)
      C = CMPLX(A(5), 1.0)
      W = CSIN(C)
      WRITE (6,108) IW
  108 FORMAT(' >CS1 ', Z8, 1X, Z8)
      C = CMPLX(823280.0, 1.0)
      W = CSIN(C)
      WRITE (6,109) IW
  109 FORMAT(' >CS2 ', Z8, 1X, Z8)
      C = CMPLX(1.0, 200.0)
      W = CSIN(C)
      WRITE (6,110) IW
  110 FORMAT(' >CS3 ', Z8, 1X, Z8)
      C = CMPLX(2.0, -200.0)
      W = CSIN(C)
      WRITE (6,111) IW
  111 FORMAT(' >CS4 ', Z8, 1X, Z8)
      C = CMPLX(1.0, A(1))
      W = CSIN(C)
      WRITE (6,112) IW
  112 FORMAT(' >CS5 ', Z8, 1X, Z8)
      C = CMPLX(1.0E6, 200.0)
      W = CSIN(C)
      WRITE (6,113) IW
  113 FORMAT(' >CS6 ', Z8, 1X, Z8)
      C = CMPLX(1.0, 200.0)
      W = CCOS(C)
      WRITE (6,114) IW
  114 FORMAT(' >CC1 ', Z8, 1X, Z8)
      C = CMPLX(-2.0, -200.0)
      W = CCOS(C)
      WRITE (6,115) IW
  115 FORMAT(' >CC2 ', Z8, 1X, Z8)
      C = CMPLX(-1.0E75, 1.0E75)
      W = CSQRT(C)
      WRITE (6,116) IW
  116 FORMAT(' >CQ1 ', Z8, 1X, Z8)
      X = CABS(CMPLX(3.0E75, 4.0E75))
      WRITE (6,117) IX
  117 FORMAT(' >CA1 ', Z8)
      C = (0.0, 0.0)
      W = C**(-1)
      WRITE (6,118) IW
  118 FORMAT(' >CP1 ', Z8, 1X, Z8)
      C = (0.0, 0.0)
      W = C**(0)
      WRITE (6,119) IW
  119 FORMAT(' >CP2 ', Z8, 1X, Z8)
      Z = DCMPLX(200.0D0, 1.0D0)
      V = CDEXP(Z)
      WRITE (6,120) IV
  120 FORMAT(' >ZE1 ', 2Z8, 1X, 2Z8)
      Z = DCMPLX(D(1), 0.0D0)
      V = CDEXP(Z)
      WRITE (6,121) IV
  121 FORMAT(' >ZE2 ', 2Z8, 1X, 2Z8)
      Z = DCMPLX(D(2), 0.0D0)
      V = CDEXP(Z)
      WRITE (6,122) IV
  122 FORMAT(' >ZE3 ', 2Z8, 1X, 2Z8)
      Z = DCMPLX(D(3), 0.0D0)
      V = CDEXP(Z)
      WRITE (6,123) IV
  123 FORMAT(' >ZE4 ', 2Z8, 1X, 2Z8)
      Z = DCMPLX(1.0D0, D(5))
      V = CDEXP(Z)
      WRITE (6,124) IV
  124 FORMAT(' >ZE5 ', 2Z8, 1X, 2Z8)
      Z = DCMPLX(1.0D0, D(6))
      V = CDEXP(Z)
      WRITE (6,125) IV
  125 FORMAT(' >ZE6 ', 2Z8, 1X, 2Z8)
      Z = DCMPLX(0.0D0, 0.0D0)
      V = CDLOG(Z)
      WRITE (6,126) IV
  126 FORMAT(' >ZL1 ', 2Z8, 1X, 2Z8)
      Z = DCMPLX(D(5), 1.0D0)
      V = CDSIN(Z)
      WRITE (6,127) IV
  127 FORMAT(' >ZS1 ', 2Z8, 1X, 2Z8)
      Z = DCMPLX(1.0D0, 200.0D0)
      V = CDSIN(Z)
      WRITE (6,128) IV
  128 FORMAT(' >ZS2 ', 2Z8, 1X, 2Z8)
      Z = DCMPLX(1.0D0, -200.0D0)
      V = CDSIN(Z)
      WRITE (6,129) IV
  129 FORMAT(' >ZS3 ', 2Z8, 1X, 2Z8)
      Z = DCMPLX(1.0D0, D(2))
      V = CDSIN(Z)
      WRITE (6,130) IV
  130 FORMAT(' >ZS4 ', 2Z8, 1X, 2Z8)
      Z = DCMPLX(2.0D0, 200.0D0)
      V = CDCOS(Z)
      WRITE (6,131) IV
  131 FORMAT(' >ZC1 ', 2Z8, 1X, 2Z8)
      Z = (0.0D0, 0.0D0)
      V = Z**(-2)
      WRITE (6,132) IV
  132 FORMAT(' >ZP1 ', 2Z8, 1X, 2Z8)
      X = EXP(A(1))
      WRITE (6,133) IX
  133 FORMAT(' >R1 ', Z8)
      X = EXP(A(2))
      WRITE (6,134) IX
  134 FORMAT(' >R2 ', Z8)
      X = SINH(A(3))
      WRITE (6,135) IX
  135 FORMAT(' >R3 ', Z8)
      X = SINH(A(4))
      WRITE (6,136) IX
  136 FORMAT(' >R4 ', Z8)
      X = SIN(A(6))
      WRITE (6,137) IX
  137 FORMAT(' >R5 ', Z8)
      E = DEXP(D(1))
      WRITE (6,138) IE
  138 FORMAT(' >D1 ', 2Z8)
      E = DEXP(D(2))
      WRITE (6,139) IE
  139 FORMAT(' >D2 ', 2Z8)
      E = DSINH(D(4))
      WRITE (6,140) IE
  140 FORMAT(' >D3 ', 2Z8)
      E = DSIN(D(5))
      WRITE (6,141) IE
  141 FORMAT(' >D4 ', 2Z8)
      END
