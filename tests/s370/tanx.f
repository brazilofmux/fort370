C     TANX -- DTAN AT 200,000 ARGUMENTS, THE BITS OF ITS RESULTS FOLDED
C     INTO A HASH (ISSUE #3): THE ONE IN ASSEMBLER DOES THE SAME
C     FLOATING-POINT OPERATIONS IN THE SAME ORDER AS THE ONE IN C, SO
C     THE TWO GIVE THE SAME HASH.  THE ARGUMENTS ARE RANDOM HFP LONGS
C     (XORSHIFT32) OF EITHER SIGN WITH CHARACTERISTICS 34-45 (1E-10 TO
C     JUST UNDER 2**20, WHERE THE ASSEMBLER HANDS OVER TO C), THEN AS
C     MANY STEPPING ACROSS (-1.6, 1.6).  AND A FEW WHOSE TANGENTS ARE
C     KNOWN, AND THOSE IT GIVES TO C.  SELF-CHECKING FOR THOSE:
C     " >NAME OK" OR " >NAME BAD"; THE HASHES ARE PRINTED, " >HASHN"
C     AND THE VALUE.
      PROGRAM TANX
      DOUBLE PRECISION X, Y
      INTEGER IX(2), IY(2), IS, IH, I, K, NBAD, IC
      EQUIVALENCE (X, IX(1)), (Y, IY(1))
      NBAD = 0
      CALL CHK('ZERO   ', DTAN(0.0D0) .EQ. 0.0D0, NBAD)
      CALL CHK('QUARTER', DABS(DTAN(0.7853981633974483D0) - 1.0D0)
     1    .LT. 1.0D-15, NBAD)
      CALL CHK('ODD    ', DTAN(-0.5D0) .EQ. -DTAN(0.5D0), NBAD)
      CALL CHK('PERIOD ', DABS(DTAN(3.0D0) - DTAN(3.0D0 - 3.141592653
     1    589793D0)) .LT. 1.0D-14, NBAD)
C     THE ARGUMENTS THE ASSEMBLER HANDS TO C: PAST FORTLIB'S LIMIT (A
C     MESSAGE, AND 1), AT A SINGULARITY (A MESSAGE, AND THE LARGEST
C     NUMBER), AND 2**20 OR MORE (PAYNE AND HANEK'S REDUCTION)
      CALL CHK('HUGEARG', DTAN(1.0D20) .EQ. 1.0D0, NBAD)
      CALL CHK('POLE   ', DTAN(1.5707963267948966D0) .GT. 7.0D75, NBAD)
      CALL CHK('BIGARG ', DABS(DTAN(2.0D6) + 0.86848531796085433D0)
     1    .LT. 1.0D-15, NBAD)
      IS = 12345
      IH = 0
      DO 10 I = 1, 100000
        CALL XSH(IS)
        IC = 52 + MOD(IAND(IS, 255), 18)
        IX(1) = IOR(ISHFT(IC, 24), IAND(IS, 16777215))
        IF (IAND(IS, 256) .NE. 0) IX(1) = IOR(IX(1), ISHFT(1, 31))
        IX(1) = IOR(IX(1), 1048576)
        CALL XSH(IS)
        IX(2) = IS
        IF (MOD(I, 100) .EQ. 0) X = X + DBLE(MOD(IS, 1000000))
        Y = DTAN(X)
        IH = IEOR(ISHFTC(IH, 5, 32), IY(1))
        IH = IEOR(ISHFTC(IH, 7, 32), IY(2))
   10 CONTINUE
      WRITE (6,1) 1, IH
    1 FORMAT(' >HASH', I1, 1X, Z8)
      IH = 0
      X = -1.6D0
      DO 20 I = 1, 100000
        X = X + 3.2D-5
        Y = DTAN(X)
        IH = IEOR(ISHFTC(IH, 5, 32), IY(1))
        IH = IEOR(ISHFTC(IH, 7, 32), IY(2))
   20 CONTINUE
      WRITE (6,1) 2, IH
      WRITE (6,2) NBAD
    2 FORMAT(' >BAD ', I2)
      END
      SUBROUTINE XSH(IS)
      INTEGER IS
      IS = IEOR(IS, ISHFT(IS, 13))
      IS = IEOR(IS, ISHFT(IS, -17))
      IS = IEOR(IS, ISHFT(IS, 5))
      END
      SUBROUTINE CHK(NAME, OK, NBAD)
      CHARACTER*7 NAME
      LOGICAL OK
      INTEGER NBAD
      IF (OK) THEN
        WRITE (6,1) NAME
    1   FORMAT(' >', A7, ' OK')
      ELSE
        WRITE (6,2) NAME
    2   FORMAT(' >', A7, ' BAD')
        NBAD = NBAD + 1
      END IF
      END
