C     THE RUNTIME'S MATHEMATICAL INTRINSICS: VALUES TO COMPARE WITH
C     AN EXACT REFERENCE ON THE HOST (tests/s370/math.sh)
      DOUBLE PRECISION X(6),Y
      REAL R
      INTEGER I
      X(1)=2.0D0
      X(2)=0.5D0
      X(3)=10.0D0
      X(4)=0.001D0
      X(5)=123.456D0
      X(6)=-2.5D0
      DO 10 I=1,6
      Y=X(I)
      WRITE(6,100) 'X',Y
      WRITE(6,100) 'SQRT',DSQRT(DABS(Y))
      WRITE(6,100) 'EXP',DEXP(Y)
      WRITE(6,100) 'LOG',DLOG(DABS(Y))
      WRITE(6,100) 'LOG10',DLOG10(DABS(Y))
      WRITE(6,100) 'SIN',DSIN(Y)
      WRITE(6,100) 'COS',DCOS(Y)
      WRITE(6,100) 'TAN',DTAN(Y)
      WRITE(6,100) 'ATAN',DATAN(Y)
      WRITE(6,100) 'ATAN2',DATAN2(Y,3.0D0)
      WRITE(6,100) 'SINH',DSINH(Y)
      WRITE(6,100) 'COSH',DCOSH(Y)
      WRITE(6,100) 'TANH',DTANH(Y)
      WRITE(6,100) 'POW',DABS(Y)**1.5D0
   10 CONTINUE
      WRITE(6,100) 'ASIN',DASIN(0.5D0)
      WRITE(6,100) 'ACOS',DACOS(0.5D0)
      WRITE(6,100) 'ASIN',DASIN(-0.9D0)
      R=2.0
      WRITE(6,101) 'RSQRT',SQRT(R)
      WRITE(6,101) 'RSIN',SIN(R)
      WRITE(6,101) 'REXP',EXP(R)
      WRITE(6,101) 'RPOW',R**0.5
  100 FORMAT(' >',A6,D25.17)
  101 FORMAT(' >',A6,E16.8)
      STOP
      END
