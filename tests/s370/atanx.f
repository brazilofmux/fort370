C     ATANX -- DATAN, DASIN, DACOS AND DATAN2 AT 100,000 ARGUMENTS
C     EACH, THE BITS OF THEIR RESULTS FOLDED INTO A HASH (ISSUE #3):
C     THE ONES IN ASSEMBLER DO THE SAME FLOATING-POINT OPERATIONS IN THE
C     SAME ORDER AS THE ONES IN C, SO THEY GIVE THE SAME HASHES.
C     DATAN'S ARGUMENTS ARE RANDOM HFP LONGS (XORSHIFT32) OF EITHER SIGN
C     AND EVERY CHARACTERISTIC; DASIN'S AND DACOS'S RANDOM IN (-1, 1),
C     HALF OF THEM WITHIN 2**-24 OR SO OF -1 OR 1, WHERE 1 - X**2 IS
C     TAKEN AS 2D - D**2; DATAN2'S Y A RANDOM HFP LONG OF EITHER SIGN
C     AND CHARACTERISTIC 30-4F, ITS X RANDOM, SOMETIMES NEGATIVE OR 0.
C     AND A FEW WHOSE VALUES ARE KNOWN, AND PAST 1 AND DATAN2(0, 0) (THE
C     C ENTRIES: FORTLIB'S MESSAGE, AND 0).  SELF-CHECKING FOR THOSE:
C     " >NAME OK" OR " >NAME BAD"; THE HASHES ARE PRINTED, " >HASHN"
C     AND THE VALUE.
      PROGRAM ATANX
      DOUBLE PRECISION X, Y, Z, PI
      INTEGER IX(2), IY(2), IS, IH, I, K, NBAD
      EQUIVALENCE (X, IX(1)), (Y, IY(1))
      NBAD = 0
      PI = 3.141592653589793D0
      CALL CHK('ATAN0  ', DATAN(0.0D0) .EQ. 0.0D0, NBAD)
      CALL CHK('ATAN1  ', DABS(DATAN(1.0D0) - PI / 4.0D0) .LT. 1.0D-15,
     1    NBAD)
      CALL CHK('ATANBIG', DABS(DATAN(-1.0D70) + PI / 2.0D0)
     1    .LT. 1.0D-15, NBAD)
      CALL CHK('ASIN1  ', DABS(DARSIN(-1.0D0) + PI / 2.0D0)
     1    .LT. 1.0D-15, NBAD)
      CALL CHK('ACOS1  ', DARCOS(1.0D0) .EQ. 0.0D0, NBAD)
      CALL CHK('ACOSM1 ', DABS(DARCOS(-1.0D0) - PI) .LT. 1.0D-15, NBAD)
      CALL CHK('ASINH  ', DABS(DARSIN(0.5D0) - PI / 6.0D0) .LT. 1.0D-15,
     1    NBAD)
      CALL CHK('ACOSH  ', DABS(DARCOS(-0.5D0) - PI * 2.0D0 / 3.0D0)
     1    .LT. 1.0D-15, NBAD)
      CALL CHK('ASINBAD', DARSIN(1.5D0) .EQ. 0.0D0, NBAD)
      CALL CHK('ACOSBAD', DARCOS(-1.5D0) .EQ. 0.0D0, NBAD)
      CALL CHK('ATAN2Y ', DABS(DATAN2(1.0D0, 0.0D0) - PI / 2.0D0)
     1    .LT. 1.0D-15, NBAD)
      CALL CHK('ATAN2PI', DABS(DATAN2(0.0D0, -1.0D0) - PI) .LT. 1.0D-15,
     1    NBAD)
      CALL CHK('ATAN2Q3', DABS(DATAN2(-1.0D0, -1.0D0) + PI * 0.75D0)
     1    .LT. 1.0D-15, NBAD)
      CALL CHK('ATAN200', DATAN2(0.0D0, 0.0D0) .EQ. 0.0D0, NBAD)
      IS = 12345
      DO 30 K = 1, 4
        IH = 0
        DO 10 I = 1, 100000
          CALL XSH(IS)
          IF (K .EQ. 1) THEN
            IX(1) = IOR(IS, 1048576)
            CALL XSH(IS)
            IX(2) = IS
            Y = DATAN(X)
          ELSE IF (K .EQ. 4) THEN
            IX(1) = IOR(IAND(IS, -2130706433), ISHFT(48 + MOD(IAND(IS,
     1          1023), 32), 24))
            IX(1) = IOR(IX(1), 1048576)
            CALL XSH(IS)
            IX(2) = IS
            CALL XSH(IS)
            Z = DBLE(IAND(IS, 2147483647)) * 1.0D-3
            IF (MOD(I, 3) .EQ. 0) Z = -Z
            IF (MOD(I, 1000) .EQ. 0) Z = 0.0D0
            Y = DATAN2(X, Z)
          ELSE
            X = DBLE(IAND(IS, 2147483647)) / 2147483648.0D0
            CALL XSH(IS)
            IF (MOD(I, 2) .EQ. 0) X = 1.0D0 - X * 6.0D-8
            X = X + DBLE(IAND(IS, 1048575)) / 1.8D21
            IF (IS .LT. 0) X = -X
            IF (K .EQ. 2) Y = DARSIN(X)
            IF (K .EQ. 3) Y = DARCOS(X)
          END IF
          IH = IEOR(ISHFTC(IH, 5, 32), IY(1))
          IH = IEOR(ISHFTC(IH, 7, 32), IY(2))
   10   CONTINUE
        WRITE (6,1) K, IH
    1   FORMAT(' >HASH', I1, 1X, Z8)
   30 CONTINUE
      WRITE (6,2) NBAD
    2 FORMAT(' >BAD ', I2)
      END
      SUBROUTINE XSH(IS)
      INTEGER IS
      IS = IEOR(IS, ISHFT(IS, 13))
      IS = IEOR(IS, ISHFT(IS, -17))
      IS = IEOR(IS, ISHFT(IS, 5))
      END
      SUBROUTINE CHK(NAME, OK, NBAD)
      CHARACTER*7 NAME
      LOGICAL OK
      INTEGER NBAD
      IF (OK) THEN
        WRITE (6,1) NAME
    1   FORMAT(' >', A7, ' OK')
      ELSE
        WRITE (6,2) NAME
    2   FORMAT(' >', A7, ' BAD')
        NBAD = NBAD + 1
      END IF
      END
