C     A REAL STORED STORAGE TO STORAGE INTO AN ELEMENT OF A DUMMY
C     ARRAY.  WITH -E AND E BOTH SPILLED (FOUR BOUNDS, FOUR FLOATING
C     REGISTERS), X(I)=-E IS AN MVC, AND X(I) IS BASE PLUS INDEX, WHICH
C     MVC CANNOT ADDRESS: THE ASSEMBLER GOT "MVC 0(2,5)(4),...", WHICH
C     IFOX00 REJECTS.  NOW THE ADDRESS IS FORMED FIRST (LA 14,0(2,5)).
      REAL X(4), Y(4)
      DATA X /-9.0, -0.5, 0.5, 9.0/
      DATA Y /9.0, 0.25, -0.25, -9.0/
      CALL CLIP(4, X, Y, 2.0, 1.0)
      WRITE (6,100) X, Y
  100 FORMAT (1X,'>MVCIDX',8F6.2)
      END
      SUBROUTINE CLIP(N,X,Y,ECARX,ECARY)
      DIMENSION X(N),Y(N)
      DO  3  I=1,N
      IF  (X(I) .LT. -ECARX)  X(I)=-ECARX
      IF  (X(I) .GT.  ECARX) X(I)= ECARX
      IF  (Y(I) .LT. -ECARY)  Y(I)=-ECARY
      IF  (Y(I).GT.  ECARY)  Y(I)= ECARY
    3 CONTINUE
      END
