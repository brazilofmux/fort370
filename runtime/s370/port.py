#!/usr/bin/env python3
"""port.py -- generate the MVS runtime, f77rt.c and f77rt.h, from the
SLOW-32 runtime runtime/libf77.c.

The SLOW-32 runtime is a copy (PROVENANCE.md) and stays one; the MVS
differences are applied here as textual replacements, each asserted to
match exactly once, so that a change upstream that moves the ground is
noticed rather than silently half-applied.  What changes:

  - every entry point gets its eight-character external name as an asm
    label (the table is backend/s370_rtnames.h's; cc370 would mangle
    f77_wr_begin and f77_wr_begin_int both to F77@WR@B);
  - a unit is the DD name FTnnF001, as IBM's Fortran names them;
  - floating-point editing goes through f77dtoa.c, the exact conversion
    (libc370's printf is not exact), and input through the compiler's
    own text-to-HFP (s370_hfp.h), truncating as H does;
  - C99's snprintf becomes sprintf, and trunc/round, which C89 lacks,
    are supplied.

Run from the repository root: python3 runtime/s370/port.py
"""
import re, sys, os

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(root)
src = open('runtime/libf77.c').read()

tab = open('backend/s370_rtnames.h').read()
m = re.search(r'static char \*s370_rt_map\[\] = \{(.*?)\n    0 \};', tab, re.S)
ext = dict(re.findall(r'"([^"]+)",\s*"([^"]+)"', m.group(1)))
def extname(c):
    if c in ext: return ext[c]
    if c.startswith('f77i_'): return ('I#' + c[5:].upper())[:8]
    sys.exit('no external name for ' + c)

protos = []
seen = set()
for mm in re.finditer(r'^(int|void|double|float|char \*)\s*(f77i?_\w+)\(([^)]*)\)\s*\{', src, re.M):
    ty, name, args = mm.group(1), mm.group(2), mm.group(3)
    if name in seen: continue
    seen.add(name)
    protos.append((ty, name, args))
h = ['/* f77rt.h -- the runtime\'s entry points, each with the eight-character',
     ' * external name the compiled code calls it by (backend/s370_rtnames.h',
     ' * holds the same table; tests/host/rtnames.sh checks they agree).',
     ' * GENERATED by runtime/s370/port.py from runtime/libf77.c. */',
     '#ifndef F77RT_H', '#define F77RT_H', '']
for ty, name, args in protos:
    h.append('%s %s(%s) __asm__("%s");' % (ty, name, args, extname(name)))
h += ['', '/* the compiler\'s names for AINT/ANINT and their DOUBLE PRECISION forms */',
      'double f77_dint(double) __asm__("F77DINT");',
      'double f77_dnint(double) __asm__("F77DNINT");',
      '', '#endif', '']
open('runtime/s370/f77rt.h', 'w').write('\n'.join(h))

s = src
def rep(old, new, count=1):
    global s
    if s.count(old) != count:
        sys.exit('port.py: expected %d of %r, found %d' % (count, old[:60], s.count(old)))
    s = s.replace(old, new)

rep('/* COPIED from slow32-public fortran/runtime/libf77.c at 2245be78 (2026-10-12).  See PROVENANCE.md. */\n/* libf77.c -- Fortran 77 formatted I/O runtime for SLOW-32.',
    '/* f77rt.c -- the Fortran 77 I/O runtime for MVS 3.8j: runtime/libf77.c\n'
    ' * (the SLOW-32 runtime, see PROVENANCE.md) with the MVS differences\n'
    ' * applied by runtime/s370/port.py, which is where to look for what\n'
    ' * changed: units are DD names FTnnF001, floating numbers are edited\n'
    ' * by the exact conversion in f77dtoa.c instead of printf, input\n'
    ' * numbers by the compiler\'s own text-to-HFP, and every entry has the\n'
    ' * eight-character external name of f77rt.h.  Built with cc370 for\n'
    ' * libc370.  GENERATED -- edit libf77.c or port.py. */\n'
    '/* libf77.c -- Fortran 77 formatted I/O runtime for SLOW-32.')
rep('#include <stdlib.h>\n', '#include <stdlib.h>\n#include "f77rt.h"\n#include "f77dtoa.h"\n#include "../../backend/s370_hfp.h"\n'
    '\n/* C89 has neither trunc nor round; libc370 is C89. */\n'
    'static double fio_trunc(double v) { return v < 0.0 ? ceil(v) : floor(v); }\n'
    'static double fio_round(double v) { return v < 0.0 ? ceil(v - 0.5) : floor(v + 0.5); }\n'
    'double f77_dint(double v) { return fio_trunc(v); }\n'
    'double f77_dnint(double v) { return fio_round(v); }\n'
    '#define trunc fio_trunc\n#define round fio_round\n'
    '\n/* Text to HFP, exactly, truncating as the compiler does for constants. */\n'
    'static double fio_strtod(const char *text) {\n'
    '    unsigned int hi, lo;\n'
    '    if (hfp_from_text(text, &hi, &lo) < 0) return 0.0;\n'
    '    return f77_hfp_make(hi, lo);\n}\n'
    '\n/* OPEN FILE=name: on MVS the name is a DD name (eight characters,\n'
    ' * upper case), and the job supplies the data set behind it.  A\n'
    ' * mode of C\'s is passed through; libc370 reads the DCB from the DD. */\n'
    'static FILE *fio_fopen(const char *name, const char *mode) {\n'
    '    char dd[16];\n'
    '    int i;\n'
    '    int n;\n'
    '    strcpy(dd, "dd:");\n'
    '    n = 3;\n'
    '    for (i = 0; name[i] && n < 11; i++) {\n'
    '        int c = (unsigned char)name[i];\n'
    '        if (c == \' \') continue;\n'
    '        if (c >= \'a\' && c <= \'z\') c = c - \'a\' + \'A\';\n'
    '        dd[n++] = (char)c;\n'
    '    }\n'
    '    dd[n] = 0;\n'
    '    return fopen(dd, mode);\n}\n')
rep('''    if (unit > 0 && unit < FIO_MAXUNIT) {
        /* Preconnected unit: the file fort.N in the working directory,
         * created on first use (gfortran's convention). */
        char nm[FIO_MAXNAME];
        FILE *f;
        snprintf(nm, sizeof nm, "fort.%d", unit);
        f = fopen(nm, "r+");
        if (!f) f = fopen(nm, "w+");''',
'''    if (unit > 0 && unit < FIO_MAXUNIT) {
        /* Preconnected unit: the DD name FTnnF001, as IBM's Fortran
         * names them, opened on first use for the direction asked. */
        char nm[FIO_MAXNAME];
        FILE *f;
        sprintf(nm, "dd:FT%02dF001", unit);
        f = fopen(nm, writing ? "w" : "r");''')
rep('''static FILE *fio_resolve(int unit, int writing) {
    if (unit >= 0 && unit < FIO_MAXUNIT && fio_ufile[unit]) return fio_ufile[unit];
    if (writing) {
        if (unit == 6) return stdout;
        if (unit == 0) return stderr;
        if (unit == 5) return stdout;    /* tolerated historically */
    } else {
        if (unit == 5 || unit == 0) return stdin;
    }
''', '''static FILE *fio_resolve(int unit, int writing) {
    if (unit >= 0 && unit < FIO_MAXUNIT && fio_ufile[unit]) return fio_ufile[unit];
    if (unit == 0) return writing ? stderr : stdin;
''')
rep('''    fprintf(stderr, "f77: unit %d is not open for %s\\n",
            unit, writing ? "WRITE" : "READ");
    exit(2);
    return 0;
}''', '''    /* no such DD: the job's SYSPRINT or SYSIN stand in for 6 and 5 */
    if (writing && unit == 6) return stdout;
    if (!writing && unit == 5) return stdin;
    fprintf(stderr, "f77: unit %d is not open for %s\\n",
            unit, writing ? "WRITE" : "READ");
    exit(2);
    return 0;
}''')
rep('''    nsig = k > 0 ? nd + 1 : nd + k;                 /* significant digits shown */
    if (nsig < 1) nsig = 1;
    snprintf(cf, sizeof cf, "%%.%dE", nsig - 1);
    snprintf(tmp, sizeof tmp, cf, v);

    p = tmp;
    neg = 0;
    if (*p == '-') { neg = 1; p++; }
    else if (*p == '+') p++;

    /* Collect the significant digits, dropping the decimal point. */
    n = 0;
    q = out;
    i = 0;
    while (p[i] && p[i] != 'E' && p[i] != 'e') {
        if (p[i] != '.') { tmp[n + 40] = p[i]; n++; }
        i++;
    }
    expv = 0;
    if (p[i] == 'E' || p[i] == 'e') expv = (int)strtol(p + i + 1, 0, 10);
    expv = expv + 1;                  /* mantissa moved below one */

    if (n == 0 || (n == 1 && tmp[40] == '0')) expv = 0;   /* exact zero */
''', '''    nsig = k > 0 ? nd + 1 : nd + k;                 /* significant digits shown */
    if (nsig < 1) nsig = 1;
    /* the exact digits, rounded half up: value = 0.digits * 10^expv */
    expv = f77_fmt_e(v, nsig, tmp + 40, &neg);
    n = nsig;
    (void)cf; (void)p; (void)i;
    if (v == 0.0) { expv = 0; neg = 0; }
''')
rep('''        snprintf(cf, sizeof cf, "%%.%df", fio_d);
        snprintf(buf, sizeof buf, cf, fv);
        /* Fw.0 keeps the decimal point ("3."); C's %.0f drops it. */
        if (fio_d == 0) strcat(buf, ".");''',
'''        f77_fmt_f(fv, fio_d, buf);
        (void)cf;''')
rep('''            snprintf(cf, sizeof cf, "%%.%df", nd - k > 0 ? nd - k : 0);
            snprintf(buf, sizeof buf, cf, v);
            if (nd - k <= 0) strcat(buf, ".");''',
'''            f77_fmt_f(v, nd - k > 0 ? nd - k : 0, buf);''')
rep('''    } else {
        snprintf(buf, sizeof buf, "%g", v);
    }
    fio_field(buf, fio_w);
    fio_consumed();
}''', '''    } else {
        fio_efmt(buf, sizeof buf, v, 6, 'E');
    }
    fio_field(buf, fio_w);
    fio_consumed();
}''')
rep('''        snprintf(cf, sizeof cf, "%%.%df", sig - ((a < 1.0 && a != 0.0) ? 0 : intd));
        snprintf(buf, sizeof buf, cf, v);''',
'''        f77_fmt_f(v, sig - ((a < 1.0 && a != 0.0) ? 0 : intd), buf);
        (void)cf;''')
rep('''        char *e;
        snprintf(cf, sizeof cf, "%%.%dE", sig - 1);
        snprintf(buf, sizeof buf, cf, v);
        e = strchr(buf, 'E');''',
'''        char *e;
        char mant[64];
        int ex;
        int ng;
        /* C's d.dddE+ee from the exact digits */
        ex = f77_fmt_e(v, sig, mant, &ng);
        sprintf(buf, "%s%c.%sE%c%02d", ng ? "-" : "", mant[0], mant + 1, ex - 1 < 0 ? '-' : '+', ex - 1 < 0 ? 1 - ex : ex - 1);
        e = strchr(buf, 'E');''')
rep('''    snprintf(num + k, sizeof num - k, "E%d", expv);
    return strtod(num, 0);''', '''    sprintf(num + k, "E%d", expv);
    return fio_strtod(num);''')
rep('''    num[i] = 0;
    return strtod(num, 0);''', '''    num[i] = 0;
    return fio_strtod(num);''')
s = re.sub(r'snprintf\(buf, sizeof buf, ', 'sprintf(buf, ', s)
s = re.sub(r'\bfopen\(nm, ', 'fio_fopen(nm, ', s)
s = re.sub(r'snprintf\(dig, sizeof dig, ', 'sprintf(dig, ', s)
s = re.sub(r'snprintf\(nm, sizeof nm, ', 'sprintf(nm, ', s)
left = [l for l in s.split('\n') if ('snprintf(' in l or 'strtod(' in l) and not l.strip().startswith('*') and 'fio_strtod' not in l]
if left:
    sys.exit('port.py: C99 calls left:\n' + '\n'.join(left))
open('runtime/s370/f77rt.c', 'w').write(s)
print('port.py: %d entry points, f77rt.c and f77rt.h written' % len(protos))
